// Java の最小構成サンプル（Hello World）
// クラス名 Main は、ファイル名 Main.java と一致させる必要があります。
public class Main {
    // main メソッドはプログラムの実行開始地点（エントリーポイント）です。
    // args にはコマンドライン引数が配列で渡されます。
    public static void main(String[] args) {
        // println は標準出力に文字列を表示し、最後に改行を入れます。
        System.out.println("Hello, World!");
    }
}
